import { type Db, type Row, openDb } from "../db.ts";
import { clearCaches } from "./cache.ts";
import { importLegacySqlite } from "./legacy.ts";

/* ---------------- connection + schema ---------------- */

let dbp: Promise<Db> | null = null;

const SCHEMA = `
create table if not exists ib_users (
  id integer generated by default as identity primary key,
  email text not null,
  name text not null,
  password_hash text not null,
  role text not null check (role in ('superadmin','admin','member')),
  status text not null default 'active' check (status in ('active','disabled')),
  must_change_password boolean not null default false,
  created_by integer,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz
);
create unique index if not exists ib_users_email on ib_users (lower(email));
create unique index if not exists ib_users_one_superadmin on ib_users (role) where role = 'superadmin';
create table if not exists ib_sessions (
  token_hash text primary key,
  user_id integer not null references ib_users(id) on delete cascade,
  created_at timestamptz not null default now(),
  last_used_at timestamptz not null default now(),
  expires_at timestamptz not null,
  ip text not null default '',
  user_agent text not null default ''
);
create index if not exists ib_sessions_user on ib_sessions(user_id);
create table if not exists ib_groups (
  id integer generated by default as identity primary key,
  name text not null,
  description text not null default '',
  created_at timestamptz not null default now()
);
create unique index if not exists ib_groups_name on ib_groups (lower(name));
create table if not exists ib_group_members (
  group_id integer not null references ib_groups(id) on delete cascade,
  user_id integer not null references ib_users(id) on delete cascade,
  primary key (group_id, user_id)
);
create index if not exists ib_group_members_user on ib_group_members(user_id);
create table if not exists ib_shares (
  id integer generated by default as identity primary key,
  kind text not null,
  ref text not null,
  label text not null default '',
  note text not null default '',
  audience text not null check (audience in ('all','group','user')),
  user_id integer references ib_users(id) on delete cascade,
  group_id integer references ib_groups(id) on delete cascade,
  starts_at timestamptz,
  expires_at timestamptz,
  pinned boolean not null default false,
  created_by integer references ib_users(id) on delete set null,
  created_at timestamptz not null default now()
);
create unique index if not exists ib_shares_unique on ib_shares (kind, ref, audience, coalesce(user_id, 0), coalesce(group_id, 0));
create table if not exists ib_grants (
  user_id integer not null references ib_users(id) on delete cascade,
  ref text not null,
  share_id integer not null references ib_shares(id) on delete cascade,
  primary key (user_id, ref, share_id)
);
create index if not exists ib_grants_share on ib_grants(share_id);
create table if not exists ib_activity (
  id bigint generated by default as identity primary key,
  user_id integer not null references ib_users(id) on delete cascade,
  at timestamptz not null default now(),
  kind text not null,
  ref text not null default '',
  label text not null default '',
  path text not null default '',
  seconds integer not null default 0
);
create index if not exists ib_activity_at on ib_activity(at);
create index if not exists ib_activity_user_at on ib_activity(user_id, at);
create table if not exists ib_daily (
  user_id integer not null references ib_users(id) on delete cascade,
  day date not null,
  watch_seconds integer not null default 0,
  opens integer not null default 0,
  primary key (user_id, day)
);
create table if not exists ib_daily_lessons (
  user_id integer not null references ib_users(id) on delete cascade,
  day date not null,
  ref text not null,
  label text not null default '',
  seconds integer not null default 0,
  primary key (user_id, day, ref)
);
create index if not exists ib_daily_lessons_day on ib_daily_lessons(day);
create table if not exists ib_audit (
  id bigint generated by default as identity primary key,
  actor_id integer references ib_users(id) on delete set null,
  at timestamptz not null default now(),
  action text not null,
  target text not null default '',
  detail text not null default ''
);
create index if not exists ib_audit_at on ib_audit(at);
create table if not exists ib_settings (key text primary key, value text not null);
create table if not exists ib_user_state (
  user_id integer not null references ib_users(id) on delete cascade,
  key text not null,
  value text not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, key)
);
`;

/* ---------------- migrations ----------------
 *
 * SCHEMA above is the idempotent baseline (create ... if not exists). Anything
 * that changes an existing table goes here instead: each entry runs once, in
 * order, inside a transaction, and is recorded in ib_migrations. Never edit an
 * entry after it has shipped; add a new one.
 */
export type Migration = { id: string; sql: string };

export const MIGRATIONS: readonly Migration[] = [
  {
    id: "0001_activity_user_id_desc",
    // onlineNow() and listActivity({ userId }) read the newest rows per member; the
    // existing (user_id, at) index does not serve "order by id desc".
    sql: "create index if not exists ib_activity_user_id_desc on ib_activity (user_id, id desc)",
  },
  {
    id: "0002_users_reset_requested_at",
    // "Forgot your password?" on the sign-in page sets this; the admin sees a badge and
    // it clears when they reset the password.
    sql: "alter table ib_users add column if not exists reset_requested_at timestamptz",
  },
];

export async function appliedMigrations(db: Db): Promise<Set<string>> {
  await db.exec("create table if not exists ib_migrations (id text primary key, applied_at timestamptz not null default now())");
  const rows = await db.query<{ id: string }>("select id from ib_migrations");
  return new Set(rows.map((r) => r.id));
}

/** Apply pending migrations. Returns the ids that ran this time. */
export async function runMigrations(db: Db, list: readonly Migration[] = MIGRATIONS): Promise<string[]> {
  const seen = new Set<string>();
  for (const m of list) {
    if (!/^\d{4}_[a-z0-9_]+$/.test(m.id)) throw new Error(`migration id must look like 0001_name: ${m.id}`);
    if (seen.has(m.id)) throw new Error(`duplicate migration id: ${m.id}`);
    seen.add(m.id);
  }
  const done = await appliedMigrations(db);
  const ran: string[] = [];
  for (const m of list) {
    if (done.has(m.id)) continue;
    await db.tx(async (t) => {
      // Two API processes booting together: the insert fails for the loser, the whole step rolls back.
      await t("insert into ib_migrations (id) values ($1)", [m.id]);
      for (const stmt of m.sql.split(/;\s*\n/).map((x) => x.trim()).filter(Boolean)) await t(stmt);
    });
    ran.push(m.id);
  }
  return ran;
}

export function store(): Promise<Db> {
  if (!dbp) {
    dbp = (async () => {
      const db = await openDb();
      await db.exec(SCHEMA);
      try {
        const ran = await runMigrations(db);
        if (ran.length) console.log(`[accounts] applied migration(s): ${ran.join(", ")}`);
      } catch (err) {
        // A failed migration must not take the API down; the next boot retries it.
        console.error("[accounts] migration failed:", err instanceof Error ? err.message : err);
      }
      await importLegacySqlite(db).catch((err) => console.warn("[accounts] legacy import skipped:", err instanceof Error ? err.message : err));
      return db;
    })();
    dbp.catch(() => {
      dbp = null;
    });
  }
  return dbp;
}

export async function openAuthStore(): Promise<Db> {
  return store();
}

export async function closeAuthStore() {
  const pending = dbp;
  dbp = null;
  clearCaches();
  if (pending) {
    const db = await pending.catch(() => null);
    await db?.close();
  }
}

export async function storeKind(): Promise<"postgres" | "pglite"> {
  return (await store()).kind;
}

export async function q<T = Row>(sql: string, params: unknown[] = []): Promise<T[]> {
  return (await store()).query<T>(sql, params);
}

export async function one<T = Row>(sql: string, params: unknown[] = []): Promise<T | null> {
  return (await q<T>(sql, params))[0] ?? null;
}
